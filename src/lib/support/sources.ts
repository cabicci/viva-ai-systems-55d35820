type Localized = Partial<Record<SupportLang, string>>;
/** The complete set of curriculum fields support may hold. Nothing else exists on a lesson. */
export type CatalogueLesson = {
  id: string;
  area: SupportArea;
  program: string;
  programName: Localized;
  titles: Localized;
  access: "free" | "plan" | "unknown";
  url: string;
};
export const CATALOGUE_LESSON_FIELDS = ["id", "area", "program", "programName", "titles", "access", "url"] as const;

export type LiveCatalogue = {
  academic?: { id: string; title: string; released?: boolean; reviewOnly?: boolean; lessons: { id: string; title: string; introductory: boolean }[] }[];
  intake?: { area: SupportArea; id: string; title: string; stations: { steps: { id: string; title: string }[] }[] }[];
  kids?: { levelId: string; lessonNumber: number; title: string }[];
};
export type LiveCatalogueByLang = Partial<Record<SupportLang, LiveCatalogue>>;

const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9_-]{0,119}$/;
const SAFE_ROUTE = /^\/learn\/[a-z]+\/[a-z0-9-]+$/;
const title = (v: unknown) => (typeof v === "string" && v.trim() && v.length <= 160 ? v.trim() : undefined);

const AI_PROGRAMS = (aiListing.programs as { id: string; name: { ar: string; en: string } }[]).filter(
  (p) => SAFE_ID.test(p.id) && title(p.name.ar) && title(p.name.en),
);

function staticLessons(): CatalogueLesson[] {
  const out: CatalogueLesson[] = [];
  const names = new Map(AI_PROGRAMS.map((p) => [p.id, p.name]));
  for (const l of aiListing.lessons as { id: string; program: string; title: { ar: string; en: string }; access: string; route: string }[]) {
    const programName = names.get(l.program);
    if (!programName || !SAFE_ID.test(l.id) || !SAFE_ROUTE.test(l.route) || !title(l.title.ar)) continue;
    out.push({
      id: l.id,
      area: "ai",
      program: l.program,
      programName: { ...programName },
      titles: { ar: title(l.title.ar), en: title(l.title.en) },
      access: l.access === "free" ? "free" : "plan",
      url: url(l.route),
    });
  }
  const techName = { ar: getPathDefinition("technical", "ar-EG").title, en: getPathDefinition("technical", "en").title };
  for (const l of technicalListing.lessons) {
    if (!SAFE_ID.test(l.id)) continue;
    out.push({
      id: l.id,
      area: "technical",
      program: "furniture",
      programName: techName,
      titles: { ar: title(l.title["ar-EG"]), en: title(l.title.en) },
      access: "unknown",
      url: url("/technical/courses/furniture/contents"),
    });
  }
  return out;
}
let STATIC: CatalogueLesson[] | null = null;
export function staticCatalogue(): CatalogueLesson[] {
  return (STATIC ??= staticLessons());
}

/** Keeps only course/lesson titles and ids from the anonymous catalogue responses. */
export function liveLessons(live: LiveCatalogueByLang): CatalogueLesson[] {
  const byId = new Map<string, CatalogueLesson>();
  const put = (lang: SupportLang, l: Omit<CatalogueLesson, "titles" | "programName">, lessonTitle: unknown, programName: unknown) => {
    const t = title(lessonTitle);
    if (!SAFE_ID.test(l.id) || !t) return;
    const key = `${l.area}:${l.program}:${l.id}`;
    const cur = byId.get(key) ?? { ...l, titles: {}, programName: {} };
    cur.titles[lang] = t;
    const p = title(programName);
    if (p) cur.programName[lang] = p;
    byId.set(key, cur);
  };
  for (const lang of ["ar", "en"] as const) {
    const c = live[lang];
    if (!c) continue;
    for (const course of c.academic ?? []) {
      if (course.released === false || course.reviewOnly === true || !SAFE_ID.test(course.id)) continue;
      for (const lesson of course.lessons ?? [])
        put(lang, { id: lesson.id, area: "academic", program: course.id, access: lesson.introductory ? "free" : "plan", url: url(`/academic/courses/${course.id}/contents`) }, lesson.title, course.title);
    }
    for (const course of c.intake ?? []) {
      if (!SAFE_ID.test(course.id)) continue;
      for (const station of course.stations ?? [])
        for (const step of station.steps ?? [])
          put(lang, { id: step.id, area: course.area, program: course.id, access: "unknown", url: url(`/courses/${course.area}/${course.id}?view=contents`) }, step.title, course.title);
    }
    for (const k of c.kids ?? []) {
      const level = KIDS_LEVELS.find((l) => l.id === k.levelId);
      if (!level || !Number.isInteger(k.lessonNumber) || k.lessonNumber < 1 || k.lessonNumber > level.lessonCount) continue;
      put(
        lang,
        { id: `${k.levelId}-${k.lessonNumber}`, area: "kids", program: k.levelId, access: k.lessonNumber <= 2 ? "free" : "plan", url: url(`/kids/${k.levelId}/${k.lessonNumber}`) },
        k.title,
        lang === "ar" ? `كيدز — ${level.ages} سنة` : `Kids — ages ${level.ages}`,
      );
    }
  }
  return [...byId.values()];
}
