/**
 * Builds lesson-registry.ts by scanning lesson content files.
 * Run after adding a new lesson file: bun run scripts/generate-lesson-registry.ts
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const lessonsDir = path.join(ROOT, "src/components/intro/lessons");
const outPath = path.join(lessonsDir, "lesson-registry.ts");

const SKIP = new Set(["index.ts", "lesson-registry.ts"]);

const entries: Array<{ id: string; exportName: string }> = [];

for (const file of readdirSync(lessonsDir).sort()) {
  if (!file.endsWith(".ts") || SKIP.has(file)) continue;
  const id = file.slice(0, -3);
  const source = readFileSync(path.join(lessonsDir, file), "utf8");
  const exportMatch = source.match(
    /export const (\w+): IntroLessonContent\b/,
  );
  if (!exportMatch) {
    throw new Error(`No IntroLessonContent export in ${file}`);
  }
  entries.push({ id, exportName: exportMatch[1] });
}

const loaderLines = entries
  .map(
    (e) =>
      `  "${e.id}": () => import("./${e.id}").then((m) => m.${e.exportName}),`,
  )
  .join("\n");

const ids = entries.map((e) => `"${e.id}"`).join(",\n  ");

const output = `import type { IntroLessonContent } from "../intro-lesson-types";

/**
 * Dynamic lesson content registry — one async chunk per lesson file.
 * Keys are stable lesson route slugs (same as curriculum lesson ids).
 *
 * Generated by scripts/generate-lesson-registry.ts — re-run after adding lessons.
 */
export const INTRO_LESSON_CONTENT_KEYS = [
  ${ids},
] as const;

export type IntroLessonContentKey = (typeof INTRO_LESSON_CONTENT_KEYS)[number];

type LessonLoader = () => Promise<IntroLessonContent>;

const LESSON_LOADERS: Record<IntroLessonContentKey, LessonLoader> = {
${loaderLines}
};

const keySet = new Set<string>(INTRO_LESSON_CONTENT_KEYS);

export function hasIntroLessonContent(
  lessonId: string,
): lessonId is IntroLessonContentKey {
  return keySet.has(lessonId);
}

export async function loadIntroLessonContent(
  lessonId: string,
): Promise<IntroLessonContent | null> {
  if (!hasIntroLessonContent(lessonId)) return null;
  return LESSON_LOADERS[lessonId]();
}

const contentCache = new Map<string, IntroLessonContent>();

export async function loadIntroLessonContentCached(
  lessonId: string,
): Promise<IntroLessonContent | null> {
  if (!hasIntroLessonContent(lessonId)) return null;
  const hit = contentCache.get(lessonId);
  if (hit) return hit;
  const loaded = await LESSON_LOADERS[lessonId]();
  contentCache.set(lessonId, loaded);
  return loaded;
}

export async function loadAllIntroLessonContent(): Promise<
  Record<IntroLessonContentKey, IntroLessonContent>
> {
  const pairs = await Promise.all(
    INTRO_LESSON_CONTENT_KEYS.map(async (id) => {
      const content = await loadIntroLessonContentCached(id);
      return [id, content!] as const;
    }),
  );
  return Object.fromEntries(pairs) as Record<
    IntroLessonContentKey,
    IntroLessonContent
  >;
}
`;

writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${entries.length} lesson loaders to ${outPath}`);
