import { describe, expect, test } from "bun:test";
import { resolve } from "node:path";
import {
  SCENES,
  SCENE_FRAMES,
  TOTAL_FRAMES,
} from "./src/lessons-generated/analyst-m5-ab-testing.gen";

const generatedPath = resolve(
  import.meta.dir,
  "src/lessons-generated/analyst-m5-ab-testing.gen.ts",
);
const acceptedPaths = [
  resolve(import.meta.dir, "../src/components/intro/lessons/analyst-m5-ab-testing.ts"),
  resolve(import.meta.dir, "../src/lib/locale-lessons/ar-EG/lessons/analyst-m5-ab-testing.json"),
  resolve(import.meta.dir, "../docs/lesson-visuals/v1/masters/analyst-m5-ab-testing.master.json"),
];

const collectStrings = (value: unknown): string[] => {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(collectStrings);
  if (value && typeof value === "object") {
    return Object.values(value).flatMap(collectStrings);
  }
  return [];
};

const derivedArabic = [
  "أهلًا، بداية الدرس",
  "مثال: صفحة A vs B",
  "مثال: ٢٠ زائر vs ٢٠٠+",
  "دورك دلوقتي",
  "شوف إجابتك صح ولا لأ.",
  "اختبر فهمك",
  "صمّم الـ A/B test بتاعك بنفسك.",
  "جاهز للتطبيق العملي؟",
];

describe("generated analyst A/B lesson encoding", () => {
  test("keeps the accepted scene structure and timing", () => {
    expect(SCENES.map((scene) => scene.card)).toEqual([
      "TitleCard",
      "BulletsCard",
      "BulletsCard",
      "CompareCard",
      "ConceptCard",
      "ConceptCard",
      "BulletsCard",
      "CTACard",
      "CTACard",
      "BulletsCard",
    ]);
    expect(SCENE_FRAMES).toEqual([
      990, 839, 1140, 919, 755, 676, 586, 351, 724, 527,
    ]);
    expect(TOTAL_FRAMES).toBe(7507);
  });

  test("contains decoded Arabic backed by the accepted sources", async () => {
    const accepted = (
      await Promise.all(acceptedPaths.map((path) => Bun.file(path).text()))
    ).join("\n");
    const arabic = collectStrings(SCENES).filter((value) =>
      /[\u0600-\u06ff]/u.test(value),
    );
    const canonical = arabic.filter((value) => accepted.includes(value));
    const derived = arabic.filter((value) => !accepted.includes(value));

    expect(arabic).toHaveLength(37);
    expect(canonical).toHaveLength(29);
    expect(derived).toEqual(derivedArabic);
    expect(JSON.stringify(SCENES)).not.toMatch(/[\u2500-\u259f]/u);
  });

  test("preserves the generated-file envelope and UTF-8 BOM", async () => {
    const bytes = new Uint8Array(await Bun.file(generatedPath).arrayBuffer());
    const text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);

    expect(Array.from(bytes.slice(0, 3))).toEqual([0xef, 0xbb, 0xbf]);
    expect(text).toMatch(
      /^\/\/ AUTO-GENERATED by remotion\/scripts\/build-lesson\.py — do NOT edit\.\r?\n/u,
    );
    expect(text).toContain(
      'import type { SceneData } from "../lesson-cards";',
    );
  });
});
